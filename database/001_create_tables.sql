CREATE TABLE USUARIOS (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME        VARCHAR(100) NOT NULL,
  LOGIN       VARCHAR(60)  NOT NULL,
  SENHA_HASH  VARCHAR(255) NOT NULL,
  ATIVO       BOOLEAN      DEFAULT TRUE NOT NULL,
  CRIADO_EM   TIMESTAMP    DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
  CONSTRAINT UQ_USUARIOS_LOGIN UNIQUE (LOGIN)
);

COMMENT ON COLUMN USUARIOS.LOGIN IS 'Sempre gravado em minúsculas';
COMMENT ON COLUMN USUARIOS.SENHA_HASH IS 'Formato: pbkdf2-sha256$<iteracoes>$<salt base64>$<hash base64>';

COMMIT;
