/*
  003 - Clientes, produtos e pedidos
  Banco: Firebird 5.0
*/

CREATE TABLE CLIENTES (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME        VARCHAR(100) NOT NULL,
  DOCUMENTO   VARCHAR(14)  NOT NULL,
  EMAIL       VARCHAR(150),
  TELEFONE    VARCHAR(20),
  ATIVO       BOOLEAN      DEFAULT TRUE NOT NULL,
  CRIADO_EM   TIMESTAMP    DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLIENTES PRIMARY KEY (ID),
  CONSTRAINT UQ_CLIENTES_DOCUMENTO UNIQUE (DOCUMENTO)
);

COMMENT ON COLUMN CLIENTES.DOCUMENTO IS 'CPF (11) ou CNPJ (14, pode ser alfanumérico), sem máscara';

CREATE TABLE PRODUTOS (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  DESCRICAO   VARCHAR(150)  NOT NULL,
  PRECO       NUMERIC(15,2) NOT NULL,
  ESTOQUE     INTEGER       DEFAULT 0 NOT NULL,
  ATIVO       BOOLEAN       DEFAULT TRUE NOT NULL,
  CRIADO_EM   TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_PRODUTOS PRIMARY KEY (ID),
  CONSTRAINT CK_PRODUTOS_PRECO CHECK (PRECO > 0),
  CONSTRAINT CK_PRODUTOS_ESTOQUE CHECK (ESTOQUE >= 0)
);

CREATE TABLE PEDIDOS (
  ID           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  CLIENTE_ID   INTEGER       NOT NULL,
  DATA_PEDIDO  TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  STATUS       VARCHAR(10)   DEFAULT 'ABERTO' NOT NULL,
  VALOR_TOTAL  NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
  CONSTRAINT FK_PEDIDOS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (ID),
  CONSTRAINT CK_PEDIDOS_STATUS CHECK (STATUS IN ('ABERTO', 'CANCELADO'))
);

CREATE TABLE PEDIDO_ITENS (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  PEDIDO_ID       INTEGER       NOT NULL,
  PRODUTO_ID      INTEGER       NOT NULL,
  QUANTIDADE      INTEGER       NOT NULL,
  PRECO_UNITARIO  NUMERIC(15,2) NOT NULL,
  VALOR_TOTAL     NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_PEDIDO_ITENS PRIMARY KEY (ID),
  CONSTRAINT FK_PEDIDO_ITENS_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDOS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_PEDIDO_ITENS_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTOS (ID),
  CONSTRAINT CK_PEDIDO_ITENS_QUANTIDADE CHECK (QUANTIDADE > 0)
);

CREATE DESCENDING INDEX IX_PEDIDOS_DATA ON PEDIDOS (DATA_PEDIDO);

COMMIT;
