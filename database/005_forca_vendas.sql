/*
  005 - Estrutura para o app Força de Vendas (delphi-fmx-forca-vendas)
  Banco: Firebird 5.0 (compatível com 3.0 ou superior)

  - código de barras no produto
  - cliente e pedido vindos do app: UUID (reenvio não duplica), localização,
    foto da fachada, assinatura e vendedor
  - faturamento informado pelo emissor de NF-e
  - ATUALIZADO_EM (mantido por trigger) para a sincronização incremental
  - visitas sem venda e sessões do refresh token
*/

ALTER TABLE PRODUTOS ADD CODIGO_BARRAS VARCHAR(14);
ALTER TABLE PRODUTOS ADD ATUALIZADO_EM TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL;

CREATE UNIQUE INDEX UQ_PRODUTOS_CODIGO_BARRAS ON PRODUTOS (CODIGO_BARRAS);
CREATE INDEX IX_PRODUTOS_ATUALIZADO_EM ON PRODUTOS (ATUALIZADO_EM);

COMMENT ON COLUMN PRODUTOS.CODIGO_BARRAS IS 'GTIN (EAN-8, UPC-A, EAN-13 ou GTIN-14), só dígitos; opcional';

ALTER TABLE CLIENTES ADD UUID CHAR(36);
ALTER TABLE CLIENTES ADD LATITUDE NUMERIC(9,6);
ALTER TABLE CLIENTES ADD LONGITUDE NUMERIC(9,6);
ALTER TABLE CLIENTES ADD FOTO BLOB SUB_TYPE BINARY;
ALTER TABLE CLIENTES ADD ATUALIZADO_EM TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL;

CREATE UNIQUE INDEX UQ_CLIENTES_UUID ON CLIENTES (UUID);
CREATE INDEX IX_CLIENTES_ATUALIZADO_EM ON CLIENTES (ATUALIZADO_EM);

COMMENT ON COLUMN CLIENTES.UUID IS 'Gerado pelo app quando o cliente nasce offline; nulo nos cadastrados pela API';
COMMENT ON COLUMN CLIENTES.FOTO IS 'JPEG da fachada, até 500 KB';

ALTER TABLE PEDIDOS ADD UUID CHAR(36);
ALTER TABLE PEDIDOS ADD USUARIO_ID INTEGER;
ALTER TABLE PEDIDOS ADD LATITUDE NUMERIC(9,6);
ALTER TABLE PEDIDOS ADD LONGITUDE NUMERIC(9,6);
ALTER TABLE PEDIDOS ADD PRECISAO_M NUMERIC(9,2);
ALTER TABLE PEDIDOS ADD OBSERVACAO VARCHAR(500);
ALTER TABLE PEDIDOS ADD ORIGEM VARCHAR(3) DEFAULT 'API' NOT NULL;
ALTER TABLE PEDIDOS ADD ASSINATURA BLOB SUB_TYPE BINARY;
ALTER TABLE PEDIDOS ADD NOTA_NUMERO INTEGER;
ALTER TABLE PEDIDOS ADD NOTA_SERIE INTEGER;
ALTER TABLE PEDIDOS ADD NOTA_CHAVE CHAR(44);
ALTER TABLE PEDIDOS ADD NOTA_AUTORIZADA_EM TIMESTAMP;
ALTER TABLE PEDIDOS ADD ATUALIZADO_EM TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL;

ALTER TABLE PEDIDOS ADD CONSTRAINT FK_PEDIDOS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID);
ALTER TABLE PEDIDOS ADD CONSTRAINT CK_PEDIDOS_ORIGEM CHECK (ORIGEM IN ('API', 'APP'));

CREATE UNIQUE INDEX UQ_PEDIDOS_UUID ON PEDIDOS (UUID);
CREATE INDEX IX_PEDIDOS_ATUALIZADO_EM ON PEDIDOS (ATUALIZADO_EM);

COMMENT ON COLUMN PEDIDOS.USUARIO_ID IS 'Vendedor que fez o pedido no app; nulo nos pedidos antigos';
COMMENT ON COLUMN PEDIDOS.ASSINATURA IS 'PNG da assinatura do cliente, até 200 KB';
COMMENT ON COLUMN PEDIDOS.NOTA_CHAVE IS 'Chave de acesso da NF-e informada pelo emissor';

CREATE TABLE VISITAS (
  ID            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  UUID          CHAR(36)      NOT NULL,
  CLIENTE_ID    INTEGER       NOT NULL,
  USUARIO_ID    INTEGER       NOT NULL,
  DATA_VISITA   TIMESTAMP     NOT NULL,
  LATITUDE      NUMERIC(9,6),
  LONGITUDE     NUMERIC(9,6),
  PRECISAO_M    NUMERIC(9,2),
  MOTIVO        VARCHAR(20)   NOT NULL,
  OBSERVACAO    VARCHAR(500),
  CRIADO_EM     TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  ATUALIZADO_EM TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  CONSTRAINT PK_VISITAS PRIMARY KEY (ID),
  CONSTRAINT UQ_VISITAS_UUID UNIQUE (UUID),
  CONSTRAINT FK_VISITAS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTES (ID),
  CONSTRAINT FK_VISITAS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
  CONSTRAINT CK_VISITAS_MOTIVO CHECK (MOTIVO IN ('AUSENTE', 'SEM_NECESSIDADE', 'SEM_ESTOQUE', 'PRECO', 'OUTRO'))
);

CREATE INDEX IX_VISITAS_USUARIO_ATUALIZADO ON VISITAS (USUARIO_ID, ATUALIZADO_EM);

COMMENT ON TABLE VISITAS IS 'Visitas a clientes que não viraram pedido (check-in do app)';

CREATE TABLE SESSOES (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  FAMILIA     CHAR(36)      NOT NULL,
  USUARIO_ID  INTEGER       NOT NULL,
  TOKEN_HASH  CHAR(64)      NOT NULL,
  DISPOSITIVO VARCHAR(100),
  CRIADA_EM   TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  EXPIRA_EM   TIMESTAMP     NOT NULL,
  REVOGADA    BOOLEAN       DEFAULT FALSE NOT NULL,
  CONSTRAINT PK_SESSOES PRIMARY KEY (ID),
  CONSTRAINT UQ_SESSOES_TOKEN_HASH UNIQUE (TOKEN_HASH),
  CONSTRAINT FK_SESSOES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID)
);

CREATE INDEX IX_SESSOES_FAMILIA ON SESSOES (FAMILIA);

COMMENT ON TABLE SESSOES IS 'Refresh tokens. Cada renovação revoga a linha e cria outra na mesma FAMILIA';
COMMENT ON COLUMN SESSOES.TOKEN_HASH IS 'SHA-256 (hex) do refresh token; o token em si nunca é gravado';
COMMENT ON COLUMN SESSOES.FAMILIA IS 'Identifica o login de origem; reuso de token revogado derruba a família inteira';

SET TERM ^ ;

CREATE TRIGGER TG_PRODUTOS_ATUALIZADO FOR PRODUTOS BEFORE UPDATE AS
BEGIN
  NEW.ATUALIZADO_EM = LOCALTIMESTAMP;
END^

CREATE TRIGGER TG_CLIENTES_ATUALIZADO FOR CLIENTES BEFORE UPDATE AS
BEGIN
  NEW.ATUALIZADO_EM = LOCALTIMESTAMP;
END^

CREATE TRIGGER TG_PEDIDOS_ATUALIZADO FOR PEDIDOS BEFORE UPDATE AS
BEGIN
  NEW.ATUALIZADO_EM = LOCALTIMESTAMP;
END^

CREATE TRIGGER TG_VISITAS_ATUALIZADO FOR VISITAS BEFORE UPDATE AS
BEGIN
  NEW.ATUALIZADO_EM = LOCALTIMESTAMP;
END^

SET TERM ; ^

COMMIT;
